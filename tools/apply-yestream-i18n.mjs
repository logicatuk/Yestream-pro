const files = fs.readdirSync(i18nDir).filter(f => f.endsWith('.json'));

for (const file of files) {
  const lang = path.basename(file, '.json');
  const filePath = path.join(i18nDir, file);
  try {
    const content = JSON.parse(fs.readFileSync(filePath, 'utf8'));
    const t = translations[lang] || translations.en;

    // 1. SETTINGS.NAV_ACCOUNT
    if (!content.SETTINGS) content.SETTINGS = {};
    content.SETTINGS.NAV_ACCOUNT = t.NAV_ACCOUNT || translations.en.NAV_ACCOUNT;

    // 2. YESTREAM Namespace
    content.YESTREAM = {
      ...translations.en,
      ...t
    };

    fs.writeFileSync(filePath, JSON.stringify(content, null, 4) + '\n', 'utf8');
    console.log(`Updated ${file} successfully with YESTREAM keys.`);
  } catch (err) {
    console.error(`Error updating ${file}:`, err);
  }
}
